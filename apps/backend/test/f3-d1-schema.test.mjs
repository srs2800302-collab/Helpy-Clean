import assert from 'node:assert/strict';
import test from 'node:test';
import { LocalDatabase } from './f3-d1-harness.mjs';
import { unpack } from '../dist/infrastructure/d1/d1-codec.js';
import {harness} from './f2-harness.mjs';import {D1AtomicRepository} from '../dist/infrastructure/d1/d1-atomic-repository.js';
test('F3 schema: exactly 35 STRICT tables, integrity-only indexes, no seed product data',()=>{
  const {sqlite:db}=new LocalDatabase();
  const tables=db.prepare("PRAGMA table_list").all().filter(t=>!t.name.startsWith('sqlite_'));
  assert.equal(tables.length,35);assert.ok(tables.every(t=>t.strict===1));
  for(const name of ['users','policies','catalog_revisions','jobs'])assert.equal(db.prepare(`SELECT count(*) AS n FROM ${name}`).get().n,0);
  assert.equal(unpack(db.prepare('SELECT value_payload FROM infrastructure_settings').get().value_payload),1572864);
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
  const columns=db.prepare('PRAGMA table_info(jobs)').all().map(x=>x.name);
  for(const c of ['financial','reservation','funds','amount'])assert.ok(!columns.includes(c));
  assert.ok(!db.prepare('PRAGMA table_info(reviews)').all().some(x=>x.name==='extra_payload'));
  assert.ok(!db.prepare('PRAGMA table_info(notification_preferences)').all().some(x=>x.name==='role_present'));
  assert.ok(!db.prepare('PRAGMA table_info(offers)').all().some(x=>x.name==='position'));
  assert.throws(()=>db.exec("UPDATE repository_meta SET revision=-1"));
  assert.throws(()=>db.exec("INSERT INTO consumed_claims VALUES ('x','other')"));
  db.exec("INSERT INTO consumed_claims VALUES ('x','login')");
  assert.throws(()=>db.exec("DELETE FROM consumed_claims"));
  assert.throws(()=>db.exec("INSERT INTO catalog_revisions VALUES ('x','x',1,1,'draft',1)"));
  db.exec("INSERT INTO catalog_revisions VALUES ('a','a',1,1,'published',1)");
  assert.throws(()=>db.exec("INSERT INTO catalog_revisions VALUES ('b','b',1,1,'published',1)"));
  assert.throws(()=>db.exec("INSERT INTO master_finance VALUES ('unknown',NULL,NULL)"));
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
});
